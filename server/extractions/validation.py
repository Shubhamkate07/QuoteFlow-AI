from typing import Any, Dict, List, Optional, Set, Tuple, Union


class ValidationSeverity(str, Enum):
    """Severity levels for quotation validation flags."""
    ERROR = "ERROR"       # Blocks automated processing or quotation approval
    WARNING = "WARNING"   # Discrepancy or missing optional field requiring human review
    INFO = "INFO"         # Informational notice or audit annotation


