"""
Deterministic Validation and Business Calculation Engine for AI-Extracted Quotations.

This module enforces strict business rules, mathematical precision, and validation flags
for quotations extracted by Gemini or any other AI service in QuoteFlow AI.

Key principles:
1. AI is NEVER responsible for calculations: All financial totals, line totals,
   tax reconciliation, and variances are calculated deterministically in Python using Decimal.
2. Structured Validation Flags: Every detected issue generates a structured flag with
   type, severity (ERROR, WARNING, INFO), field path, expected value, actual value, and explanation.
3. Zero Tolerance for Data Corruption: Negative prices, invalid data types, negative quantities,
   and arithmetic discrepancies are caught before data can enter official procurement records.
"""

from dataclasses import asdict, dataclass, field
from datetime import date, datetime
from decimal import Decimal, InvalidOperation, ROUND_HALF_UP
from enum import Enum
