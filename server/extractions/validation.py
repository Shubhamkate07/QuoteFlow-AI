@dataclass
class ValidationFlag:
    """
    Structured validation flag generated by the deterministic validator.
    """
    flag_type: str
    severity: str
    field: str
    explanation: str
    expected_value: Optional[Any] = None
    actual_value: Optional[Any] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert flag to JSON-serializable dictionary."""
        return {
            "flag_type": self.flag_type,
            "severity": self.severity,
            "field": self.field,
            "expected_value": self.expected_value,
            "actual_value": self.actual_value,
            "explanation": self.explanation,
        }


@dataclass
class ValidationReport:
    """
    Comprehensive validation report detailing mathematical calculations,
    discrepancy audits, and all generated validation flags.
    """
    is_valid: bool = True               # True if zero ERROR flags
    has_errors: bool = False            # True if any ERROR flags exist
    has_warnings: bool = False          # True if any WARNING flags exist
    is_math_consistent: bool = True     # True if financial calculations match within tolerance
    flags: List[ValidationFlag] = field(default_factory=list)

    # Deterministic Python Calculations
    calculated_items_subtotal: Decimal = Decimal('0.00')
    calculated_tax_total: Decimal = Decimal('0.00')
    calculated_grand_total: Decimal = Decimal('0.00')
    total_variance: Decimal = Decimal('0.00')

    # Parsed and Normalized Data
    normalized_currency: str = "USD"
    parsed_quotation_date: Optional[date] = None
    parsed_validity_date: Optional[date] = None
    items_count: int = 0

    def add_flag(self, flag: ValidationFlag) -> None:
        """Add a flag and update report status flags."""
        self.flags.append(flag)
        if flag.severity == ValidationSeverity.ERROR.value:
            self.has_errors = True
            self.is_valid = False
            if flag.flag_type in {
                ValidationFlagType.INCORRECT_LINE_TOTAL.value,
                ValidationFlagType.SUBTOTAL_INCONSISTENCY.value,
                ValidationFlagType.TAX_CALCULATION_INCONSISTENCY.value,
                ValidationFlagType.GRAND_TOTAL_INCONSISTENCY.value,
                ValidationFlagType.DATE_ORDER_INVERTED.value,
            }:
                self.is_math_consistent = False
        elif flag.severity == ValidationSeverity.WARNING.value:
            self.has_warnings = True

    @property
    def error_count(self) -> int:
        return sum(1 for f in self.flags if f.severity == ValidationSeverity.ERROR.value)

    @property
    def warning_count(self) -> int:
        return sum(1 for f in self.flags if f.severity == ValidationSeverity.WARNING.value)

    @property
    def info_count(self) -> int:
        return sum(1 for f in self.flags if f.severity == ValidationSeverity.INFO.value)

    def flags_by_severity(self, severity: Union[ValidationSeverity, str]) -> List[ValidationFlag]:
        target = severity.value if isinstance(severity, ValidationSeverity) else str(severity)
        return [f for f in self.flags if f.severity == target]

    def flags_by_field(self, field_path: str) -> List[ValidationFlag]:
        return [f for f in self.flags if f.field == field_path]

    def to_dict(self) -> Dict[str, Any]:
        """Convert entire report to JSON-serializable dictionary."""
        return {
            "is_valid": self.is_valid,
            "has_errors": self.has_errors,
            "has_warnings": self.has_warnings,
            "is_math_consistent": self.is_math_consistent,
            "error_count": self.error_count,
            "warning_count": self.warning_count,
            "info_count": self.info_count,
            "calculated_items_subtotal": float(self.calculated_items_subtotal),
            "calculated_tax_total": float(self.calculated_tax_total),
            "calculated_grand_total": float(self.calculated_grand_total),
            "total_variance": float(self.total_variance),
            "normalized_currency": self.normalized_currency,
            "parsed_quotation_date": self.parsed_quotation_date.isoformat() if self.parsed_quotation_date else None,
            "parsed_validity_date": self.parsed_validity_date.isoformat() if self.parsed_validity_date else None,
            "items_count": self.items_count,
            "flags": [f.to_dict() for f in self.flags],
        }


class QuotationCalculator:
    """
    Pure Python arithmetic engine using Decimal with half-up rounding.
    Guarantees deterministic math independent of LLMs or floating point artifacts.
    """

    TWO_PLACES = Decimal('0.01')

    @classmethod
    def to_decimal(cls, val: Any) -> Optional[Decimal]:
        """Safely converts arbitrary numeric/string input to a 2-decimal-place Decimal."""
        if val is None or val == "":
            return None
        if isinstance(val, (int, float, str, Decimal)):
            try:
                # Clean string representations (e.g., "$1,250.00" -> "1250.00", "13,75" -> "13.75", "1.425,50" -> "1425.50")
                if isinstance(val, str):
                    s = val.strip()
                    s = re.sub(r'[\$\€\£\₹\s]', '', s)
                    if not s:
                        return None
                    if ',' in s and '.' in s:
                        if s.rfind(',') > s.rfind('.'):
                            # European format: 1.425,50 -> 1425.50
                            s = s.replace('.', '').replace(',', '.')
                        else:
                            # US format: 1,425.50 -> 1425.50
                            s = s.replace(',', '')
                    elif ',' in s and '.' not in s:
                        parts = s.split(',')
                        if len(parts) == 2 and len(parts[1]) in (1, 2):
                            # Decimal comma: 13,75 -> 13.75
                            s = parts[0] + '.' + parts[1]
                        else:
                            s = s.replace(',', '')
                    d = Decimal(s)
                else:
                    d = Decimal(str(val))
                return d.quantize(cls.TWO_PLACES, rounding=ROUND_HALF_UP)
            except (InvalidOperation, TypeError, ValueError):
                return None
        return None

    @classmethod
    def calculate_line_total(
        cls,
        quantity: Decimal,
        unit_price: Decimal,
        discount: Decimal = Decimal('0.00'),
        tax: Decimal = Decimal('0.00'),
    ) -> Decimal:
        """
        Calculates line item extended total: (quantity * unit_price) - discount + tax.
        """
        line_base = (quantity * unit_price).quantize(cls.TWO_PLACES, rounding=ROUND_HALF_UP)
        total = line_base - discount + tax
        return total.quantize(cls.TWO_PLACES, rounding=ROUND_HALF_UP)

    @classmethod
    def calculate_subtotal(cls, line_items: List[Dict[str, Any]]) -> Decimal:
        """
        Calculates quotation subtotal: sum((quantity * unit_price) - line_discount).
        """
        subtotal = Decimal('0.00')
        for item in line_items:
            qty = cls.to_decimal(item.get('quantity'))
            price = cls.to_decimal(item.get('unit_price'))
            disc = cls.to_decimal(item.get('discount')) or Decimal('0.00')
            if qty is not None and price is not None:
                line_val = (qty * price) - disc
                subtotal += line_val
            elif item.get('total') is not None:
                tot = cls.to_decimal(item.get('total'))
                if tot is not None:
                    subtotal += tot
        return subtotal.quantize(cls.TWO_PLACES, rounding=ROUND_HALF_UP)

    @classmethod
    def calculate_itemized_tax(cls, line_items: List[Dict[str, Any]]) -> Decimal:
        """Calculates sum of itemized line taxes."""
        tax_sum = Decimal('0.00')
        for item in line_items:
            t = cls.to_decimal(item.get('tax'))
            if t is not None:
                tax_sum += t
        return tax_sum.quantize(cls.TWO_PLACES, rounding=ROUND_HALF_UP)

    @classmethod
    def calculate_grand_total(
        cls,
        subtotal: Decimal,
        tax: Decimal = Decimal('0.00'),
        shipping: Decimal = Decimal('0.00'),
        discount: Decimal = Decimal('0.00'),
    ) -> Decimal:
        """
        Calculates final grand total: subtotal - discount + tax + shipping.
        """
        grand = subtotal - discount + tax + shipping
        return grand.quantize(cls.TWO_PLACES, rounding=ROUND_HALF_UP)


class QuotationDeterministicValidator:
    """
    Comprehensive deterministic validator for AI-extracted quotations.
    Executes all required verification checks and produces a structured ValidationReport.
    """

    TOLERANCE = Decimal('0.05')  # $0.05 cent tolerance for rounding

    DATE_FORMATS = (
        '%Y-%m-%d',
        '%d/%m/%Y',
        '%m/%d/%Y',
        '%d-%m-%Y',
        '%B %d, %Y',
        '%b %d, %Y',
        '%d %b %Y',
        '%Y/%m/%d',
        '%d.%m.%Y',
    )

    @classmethod
    def validate(cls, data: Union[Dict[str, Any], Any]) -> ValidationReport:
        """
        Primary entry point. Validates either a Pydantic model instance or raw dictionary.
        """
        report = ValidationReport()

        # Coerce Pydantic models to dict if needed
        if hasattr(data, 'model_dump'):
            raw_data = data.model_dump()
        elif isinstance(data, dict):
            raw_data = data
        else:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.INVALID_DATA_TYPE.value,
                severity=ValidationSeverity.ERROR.value,
                field="root",
                expected_value="dictionary or QuotationExtractionSchema",
                actual_value=type(data).__name__,
                explanation=f"Extraction payload must be a dictionary or schema object, got {type(data).__name__}.",
            ))
            return report

        supplier = raw_data.get('supplier')
        quotation = raw_data.get('quotation')
        line_items = raw_data.get('line_items')
        commercial_terms = raw_data.get('commercial_terms') or {}

        # 1. Structural & Type Checks on Root Blocks
        cls._validate_root_structure(supplier, quotation, line_items, report)
        if report.has_errors and (supplier is None or quotation is None):
            # Cannot proceed with deep audits if root blocks are missing
            return report

        supplier = supplier or {}
        quotation = quotation or {}
        line_items = line_items if isinstance(line_items, list) else []

        # 2. Supplier Information Validation
        cls._validate_supplier(supplier, report)

        # 3. Currency Validation
        cls._validate_currency(quotation, report)

        # 4. Date Validation (Format, Chronology, Realistic Range)
        cls._validate_dates(quotation, report)

        # 5. Line Items Validation (Data types, negative quantities/prices, missing units/specs, duplicates, arithmetic)
        cls._validate_line_items(line_items, report)

        # 6. Header Financial Totals & Grand Total Reconciliation
        cls._validate_totals_and_reconciliation(quotation, line_items, report)

        return report

    @classmethod
    def _validate_root_structure(
        cls,
        supplier: Any,
        quotation: Any,
        line_items: Any,
        report: ValidationReport,
    ) -> None:
        """Validates that required root blocks exist and have correct types."""
        if supplier is None:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.REQUIRED_FIELD_MISSING.value,
                severity=ValidationSeverity.ERROR.value,
                field="supplier",
                expected_value="object",
                actual_value=None,
                explanation="Supplier information block is completely missing.",
            ))
        elif not isinstance(supplier, dict):
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.INVALID_DATA_TYPE.value,
                severity=ValidationSeverity.ERROR.value,
                field="supplier",
                expected_value="object",
                actual_value=type(supplier).__name__,
                explanation=f"Expected 'supplier' to be an object, got {type(supplier).__name__}.",
            ))

        if quotation is None:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.REQUIRED_FIELD_MISSING.value,
                severity=ValidationSeverity.ERROR.value,
                field="quotation",
                expected_value="object",
                actual_value=None,
                explanation="Quotation financial metadata block is completely missing.",
            ))
        elif not isinstance(quotation, dict):
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.INVALID_DATA_TYPE.value,
                severity=ValidationSeverity.ERROR.value,
                field="quotation",
                expected_value="object",
                actual_value=type(quotation).__name__,
                explanation=f"Expected 'quotation' to be an object, got {type(quotation).__name__}.",
            ))

        if line_items is None:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.REQUIRED_FIELD_MISSING.value,
                severity=ValidationSeverity.ERROR.value,
                field="line_items",
                expected_value="list",
                actual_value=None,
                explanation="Line items list is completely missing from extraction.",
            ))
        elif not isinstance(line_items, list):
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.INVALID_DATA_TYPE.value,
                severity=ValidationSeverity.ERROR.value,
                field="line_items",
                expected_value="list",
                actual_value=type(line_items).__name__,
                explanation=f"Expected 'line_items' to be a list, got {type(line_items).__name__}.",
            ))
        elif len(line_items) == 0:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.REQUIRED_FIELD_MISSING.value,
                severity=ValidationSeverity.ERROR.value,
                field="line_items",
                expected_value="at least 1 line item",
                actual_value="0 items",
                explanation="Quotation contains zero line items. Procurement quotations must have at least one bill of materials entry.",
            ))

    @classmethod
    def _validate_supplier(cls, supplier: Dict[str, Any], report: ValidationReport) -> None:
        """Validates supplier identification and quotation number."""
        supplier_name = supplier.get('supplier_name')
        if not supplier_name or not str(supplier_name).strip():
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.MISSING_SUPPLIER.value,
                severity=ValidationSeverity.ERROR.value,
                field="supplier.supplier_name",
                expected_value="Non-empty supplier company name",
                actual_value=supplier_name,
                explanation="Supplier name was not detected. A quotation cannot be processed without identifying the vendor.",
            ))

        quote_number = supplier.get('quotation_number')
        if not quote_number or not str(quote_number).strip():
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.MISSING_QUOTATION_NUMBER.value,
                severity=ValidationSeverity.WARNING.value,
                field="supplier.quotation_number",
                expected_value="Quotation reference number or proposal ID",
                actual_value=quote_number,
                explanation="Quotation reference number was not detected. Review recommended before issuance.",
            ))

    @classmethod
    def _validate_currency(cls, quotation: Dict[str, Any], report: ValidationReport) -> None:
        """Validates and normalizes 3-letter ISO 4217 currency code."""
        raw_currency = quotation.get('currency')
        if not raw_currency or not str(raw_currency).strip():
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.REQUIRED_FIELD_MISSING.value,
                severity=ValidationSeverity.WARNING.value,
                field="quotation.currency",
                expected_value="ISO 4217 3-letter currency code (e.g. USD, EUR, GBP)",
                actual_value=raw_currency,
                explanation="Currency code was not detected on the quotation. Defaulting to USD.",
            ))
            report.normalized_currency = "USD"
            return

        clean_currency = re.sub(r'[^A-Za-z]', '', str(raw_currency)).strip().upper()
        if clean_currency in ISO_4217_CURRENCIES:
            report.normalized_currency = clean_currency
        else:
            report.normalized_currency = clean_currency[:3] if len(clean_currency) >= 3 else "USD"
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.INVALID_CURRENCY.value,
                severity=ValidationSeverity.ERROR.value,
                field="quotation.currency",
                expected_value="Valid ISO 4217 currency code (e.g. USD, EUR, GBP, INR, JPY)",
                actual_value=raw_currency,
                explanation=f"Currency '{raw_currency}' is not a recognized ISO 4217 currency code.",
            ))

    @classmethod
    def _parse_date_string(cls, date_str: Any) -> Tuple[Optional[date], Optional[str]]:
        """Attempts to parse arbitrary date string across common procurement formats."""
        if not date_str or not isinstance(date_str, str):
            return None, "Date value is null or not a string."
        clean = date_str.strip()
        for fmt in cls.DATE_FORMATS:
            try:
                parsed = datetime.strptime(clean, fmt).date()
                return parsed, None
            except ValueError:
                continue
        return None, f"String '{date_str}' does not match standard date formats (expected YYYY-MM-DD or DD/MM/YYYY)."

    @classmethod
    def _validate_dates(cls, quotation: Dict[str, Any], report: ValidationReport) -> None:
        """Validates issuance date and expiration date formats, chronology, and reasonableness."""
        raw_quote_date = quotation.get('quotation_date')
        raw_validity_date = quotation.get('validity_date')

        parsed_quote_date = None
        parsed_validity_date = None

        # 1. Quotation Date
        if raw_quote_date:
            parsed_quote_date, err = cls._parse_date_string(raw_quote_date)
            if not parsed_quote_date:
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.INVALID_DATE_FORMAT.value,
                    severity=ValidationSeverity.ERROR.value,
                    field="quotation.quotation_date",
                    expected_value="Valid calendar date in YYYY-MM-DD format",
                    actual_value=raw_quote_date,
                    explanation=f"Quotation issue date '{raw_quote_date}' could not be parsed: {err}",
                ))
            else:
                report.parsed_quotation_date = parsed_quote_date
                # Range check: between 5 years in past and 1 year in future
                today = date.today()
                days_diff = (parsed_quote_date - today).days
                if days_diff < -1825:  # > 5 years ago
                    report.add_flag(ValidationFlag(
                        flag_type=ValidationFlagType.DATE_OUT_OF_RANGE.value,
                        severity=ValidationSeverity.WARNING.value,
                        field="quotation.quotation_date",
                        expected_value="Date within the last 5 years",
                        actual_value=parsed_quote_date.isoformat(),
                        explanation=f"Quotation date {parsed_quote_date.isoformat()} is more than 5 years in the past.",
                    ))
                elif days_diff > 365:  # > 1 year in future
                    report.add_flag(ValidationFlag(
                        flag_type=ValidationFlagType.DATE_OUT_OF_RANGE.value,
                        severity=ValidationSeverity.WARNING.value,
                        field="quotation.quotation_date",
                        expected_value="Date not more than 1 year in the future",
                        actual_value=parsed_quote_date.isoformat(),
                        explanation=f"Quotation date {parsed_quote_date.isoformat()} is more than 1 year in the future.",
                    ))
        else:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.REQUIRED_FIELD_MISSING.value,
                severity=ValidationSeverity.WARNING.value,
                field="quotation.quotation_date",
                expected_value="Quotation issue date (YYYY-MM-DD)",
                actual_value=None,
                explanation="Quotation issue date was not detected.",
            ))

        # 2. Validity Date
        if raw_validity_date:
            parsed_validity_date, err = cls._parse_date_string(raw_validity_date)
            if not parsed_validity_date:
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.INVALID_DATE_FORMAT.value,
                    severity=ValidationSeverity.ERROR.value,
                    field="quotation.validity_date",
                    expected_value="Valid calendar date in YYYY-MM-DD format",
                    actual_value=raw_validity_date,
                    explanation=f"Price validity expiration date '{raw_validity_date}' could not be parsed: {err}",
                ))
            else:
                report.parsed_validity_date = parsed_validity_date
        else:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.REQUIRED_FIELD_MISSING.value,
                severity=ValidationSeverity.INFO.value,
                field="quotation.validity_date",
                expected_value="Quotation expiration date (YYYY-MM-DD)",
                actual_value=None,
                explanation="Price validity date was not specified by the supplier.",
            ))

        # 3. Chronological Consistency: Validity >= Quotation Date
        if parsed_quote_date and parsed_validity_date:
            if parsed_validity_date < parsed_quote_date:
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.DATE_ORDER_INVERTED.value,
                    severity=ValidationSeverity.ERROR.value,
                    field="quotation.validity_date",
                    expected_value=f">= {parsed_quote_date.isoformat()}",
                    actual_value=parsed_validity_date.isoformat(),
                    explanation=(
                        f"Date anomaly: Validity date ({parsed_validity_date.isoformat()}) "
                        f"is earlier than quotation issue date ({parsed_quote_date.isoformat()})."
                    ),
                ))

    @classmethod
    def _validate_line_items(cls, line_items: List[Dict[str, Any]], report: ValidationReport) -> None:
        """Audits individual line items for math, types, negative quantities, missing units, and duplicates."""
        report.items_count = len(line_items)

        seen_models: Dict[str, int] = {}
        seen_descriptions: Dict[str, int] = {}

        for idx, item in enumerate(line_items, start=1):
            if not isinstance(item, dict):
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.INVALID_DATA_TYPE.value,
                    severity=ValidationSeverity.ERROR.value,
                    field=f"line_items[{idx-1}]",
                    expected_value="dictionary",
                    actual_value=type(item).__name__,
                    explanation=f"Line item #{idx} is not a valid object, got {type(item).__name__}.",
                ))
                continue

            line_ref = f"Line #{item.get('line_number') or idx}"
            desc = (item.get('description') or '').strip()
            model = (item.get('model') or item.get('model_number') or '').strip()

            # Description check
            if not desc:
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.REQUIRED_FIELD_MISSING.value,
                    severity=ValidationSeverity.ERROR.value,
                    field=f"line_items[{idx-1}].description",
                    expected_value="Non-empty product/service description",
                    actual_value=desc,
                    explanation=f"{line_ref}: Item description is missing.",
                ))

            # Duplicate Part/Model Number Detection
            if model:
                norm_model = model.upper()
                if norm_model in seen_models:
                    prev_line = seen_models[norm_model]
                    report.add_flag(ValidationFlag(
                        flag_type=ValidationFlagType.DUPLICATE_ITEM.value,
                        severity=ValidationSeverity.WARNING.value,
                        field=f"line_items[{idx-1}].model",
                        expected_value="Unique model/part number per line item",
                        actual_value=model,
                        explanation=f"{line_ref}: Duplicate part/model number '{model}' detected (previously appeared on line #{prev_line}).",
                    ))
                else:
                    seen_models[norm_model] = idx

            # Duplicate Description Detection
            if desc and len(desc) >= 5:
                norm_desc = re.sub(r'\s+', ' ', desc.lower())
                if norm_desc in seen_descriptions and not model:
                    prev_line = seen_descriptions[norm_desc]
                    report.add_flag(ValidationFlag(
                        flag_type=ValidationFlagType.DUPLICATE_ITEM.value,
                        severity=ValidationSeverity.WARNING.value,
                        field=f"line_items[{idx-1}].description",
                        expected_value="Unique item description",
                        actual_value=desc,
                        explanation=f"{line_ref}: Duplicate item description detected (previously appeared on line #{prev_line}).",
                    ))
                else:
                    seen_descriptions[norm_desc] = idx

            # Quantity and Unit Validation
            raw_qty = item.get('quantity')
            qty_decimal = cls._validate_numeric_field(
                val=raw_qty,
                field_name=f"line_items[{idx-1}].quantity",
                item_label=line_ref,
                allow_negative=False,
                allow_zero=False,
                report=report,
            )

            raw_unit = item.get('unit')
            clean_unit = str(raw_unit).strip().upper() if raw_unit else ""
            if not clean_unit:
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.MISSING_UNIT.value,
                    severity=ValidationSeverity.WARNING.value,
                    field=f"line_items[{idx-1}].unit",
                    expected_value="Unit of measure (e.g. PCS, EA, KG, M, BOX)",
                    actual_value=raw_unit,
                    explanation=f"{line_ref}: Unit of measurement is missing.",
                ))
            elif qty_decimal is not None:
                # Check for fractional quantity on discrete units
                if clean_unit in DISCRETE_UNITS and (qty_decimal % Decimal('1.00') != Decimal('0.00')):
                    report.add_flag(ValidationFlag(
                        flag_type=ValidationFlagType.QUANTITY_INCONSISTENCY.value,
                        severity=ValidationSeverity.WARNING.value,
                        field=f"line_items[{idx-1}].quantity",
                        expected_value=f"Integer quantity for discrete unit '{clean_unit}'",
                        actual_value=float(qty_decimal),
                        explanation=f"{line_ref}: Fractional quantity ({qty_decimal}) quoted for discrete unit '{clean_unit}'.",
                    ))

            # Unit Price Validation
            raw_price = item.get('unit_price')
            price_decimal = cls._validate_numeric_field(
                val=raw_price,
                field_name=f"line_items[{idx-1}].unit_price",
                item_label=line_ref,
                allow_negative=False,
                allow_zero=True,
                report=report,
            )

            # Discount and Tax Validation
            raw_disc = item.get('discount')
            disc_decimal = Decimal('0.00')
            if raw_disc is not None:
                d = cls._validate_numeric_field(
                    val=raw_disc,
                    field_name=f"line_items[{idx-1}].discount",
                    item_label=line_ref,
                    allow_negative=False,
                    allow_zero=True,
                    report=report,
                )
                if d is not None:
                    disc_decimal = d

            raw_tax = item.get('tax')
            tax_decimal = Decimal('0.00')
            if raw_tax is not None:
                t = cls._validate_numeric_field(
                    val=raw_tax,
                    field_name=f"line_items[{idx-1}].tax",
                    item_label=line_ref,
                    allow_negative=False,
                    allow_zero=True,
                    report=report,
                )
                if t is not None:
                    tax_decimal = t

            # Line Total & Arithmetic Verification
            raw_total = item.get('total')
            stated_total = cls._validate_numeric_field(
                val=raw_total,
                field_name=f"line_items[{idx-1}].total",
                item_label=line_ref,
                allow_negative=False,
                allow_zero=True,
                report=report,
            )

            if qty_decimal is not None and price_decimal is not None:
                expected_total = QuotationCalculator.calculate_line_total(
                    quantity=qty_decimal,
                    unit_price=price_decimal,
                    discount=disc_decimal,
                    tax=tax_decimal,
                )
                if stated_total is not None:
                    diff = abs(stated_total - expected_total)
                    if diff > cls.TOLERANCE:
                        report.add_flag(ValidationFlag(
                            flag_type=ValidationFlagType.INCORRECT_LINE_TOTAL.value,
                            severity=ValidationSeverity.ERROR.value,
                            field=f"line_items[{idx-1}].total",
                            expected_value=float(expected_total),
                            actual_value=float(stated_total),
                            explanation=(
                                f"{line_ref}: Stated line total ({stated_total}) differs from expected "
                                f"({qty_decimal} * {price_decimal} - discount {disc_decimal} + tax {tax_decimal} = {expected_total}) "
                                f"by {diff}."
                            ),
                        ))

            # Missing Technical Specifications Check
            specs = item.get('specifications')
            if not specs or len(specs) == 0:
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.MISSING_SPECIFICATIONS.value,
                    severity=ValidationSeverity.INFO.value,
                    field=f"line_items[{idx-1}].specifications",
                    expected_value="List of technical specifications or parameters",
                    actual_value=specs,
                    explanation=f"{line_ref}: No technical specifications or dimensions were detected for this line item.",
                ))

    @classmethod
    def _validate_numeric_field(
        cls,
        val: Any,
        field_name: str,
        item_label: str,
        allow_negative: bool,
        allow_zero: bool,
        report: ValidationReport,
    ) -> Optional[Decimal]:
        """
        Validates data type, non-negativity, and non-zeroness of a numeric field.
        """
        if val is None or val == "":
            return None

        # Check for boolean masquerading as number (True/False are subclasses of int in Python)
        if isinstance(val, bool):
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.INVALID_DATA_TYPE.value,
                severity=ValidationSeverity.ERROR.value,
                field=field_name,
                expected_value="numeric",
                actual_value=val,
                explanation=f"{item_label}: Expected numeric value for '{field_name}', got boolean '{val}'.",
            ))
            return None

        dec = QuotationCalculator.to_decimal(val)
        if dec is None:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.INVALID_DATA_TYPE.value,
                severity=ValidationSeverity.ERROR.value,
                field=field_name,
                expected_value="numeric",
                actual_value=val,
                explanation=f"{item_label}: Value '{val}' for '{field_name}' could not be converted to a valid number.",
            ))
            return None

        if not allow_negative and dec < Decimal('0.00'):
            flag_type = (
                ValidationFlagType.NEGATIVE_QUANTITY.value
                if "quantity" in field_name
                else ValidationFlagType.NEGATIVE_PRICE.value
            )
            report.add_flag(ValidationFlag(
                flag_type=flag_type,
                severity=ValidationSeverity.ERROR.value,
                field=field_name,
                expected_value=">= 0.00" if allow_zero else "> 0.00",
                actual_value=float(dec),
                explanation=f"{item_label}: '{field_name}' cannot be negative ({dec}).",
            ))
            return dec

        if not allow_zero and dec == Decimal('0.00'):
            flag_type = (
                ValidationFlagType.QUANTITY_INCONSISTENCY.value
                if "quantity" in field_name
                else ValidationFlagType.INCORRECT_LINE_TOTAL.value
            )
            report.add_flag(ValidationFlag(
                flag_type=flag_type,
                severity=ValidationSeverity.ERROR.value,
                field=field_name,
                expected_value="> 0.00",
                actual_value=0.0,
                explanation=f"{item_label}: '{field_name}' must be greater than zero.",
            ))
            return dec

        return dec

    @classmethod
    def _validate_totals_and_reconciliation(
        cls,
        quotation: Dict[str, Any],
        line_items: List[Dict[str, Any]],
        report: ValidationReport,
    ) -> None:
        """
        Reconciles header subtotal, tax, discount, shipping, and grand total against line item arithmetic.
        """
        # 1. Calculate deterministic item subtotal from items
        calculated_subtotal = QuotationCalculator.calculate_subtotal(line_items)
        report.calculated_items_subtotal = calculated_subtotal

        # 2. Extract header totals
        raw_subtotal = quotation.get('subtotal')
        stated_subtotal = cls._validate_numeric_field(
            val=raw_subtotal,
            field_name="quotation.subtotal",
            item_label="Quotation Header",
            allow_negative=False,
            allow_zero=True,
            report=report,
        )

        raw_tax = quotation.get('tax')
        stated_tax = cls._validate_numeric_field(
            val=raw_tax,
            field_name="quotation.tax",
            item_label="Quotation Header",
            allow_negative=False,
            allow_zero=True,
            report=report,
        ) or Decimal('0.00')

        raw_discount = quotation.get('discount')
        stated_discount = cls._validate_numeric_field(
            val=raw_discount,
            field_name="quotation.discount",
            item_label="Quotation Header",
            allow_negative=False,
            allow_zero=True,
            report=report,
        ) or Decimal('0.00')

        raw_shipping = quotation.get('shipping')
        stated_shipping = cls._validate_numeric_field(
            val=raw_shipping,
            field_name="quotation.shipping",
            item_label="Quotation Header",
            allow_negative=False,
            allow_zero=True,
            report=report,
        ) or Decimal('0.00')

        raw_grand_total = quotation.get('grand_total')
        stated_grand_total = cls._validate_numeric_field(
            val=raw_grand_total,
            field_name="quotation.grand_total",
            item_label="Quotation Header",
            allow_negative=False,
            allow_zero=True,
            report=report,
        )

        # 3. Subtotal Reconciliation
        if stated_subtotal is not None and len(line_items) > 0:
            subtotal_diff = abs(stated_subtotal - calculated_subtotal)
            if subtotal_diff > cls.TOLERANCE:
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.SUBTOTAL_INCONSISTENCY.value,
                    severity=ValidationSeverity.ERROR.value,
                    field="quotation.subtotal",
                    expected_value=float(calculated_subtotal),
                    actual_value=float(stated_subtotal),
                    explanation=(
                        f"Subtotal discrepancy: Sum of line items ({calculated_subtotal}) differs from "
                        f"stated document subtotal ({stated_subtotal}) by {subtotal_diff}."
                    ),
                ))

        # 4. Tax Calculation Inconsistencies
        itemized_tax = QuotationCalculator.calculate_itemized_tax(line_items)
        report.calculated_tax_total = itemized_tax if itemized_tax > Decimal('0.00') else stated_tax

        # If line items explicitly specify taxes, check that their sum equals stated tax
        if itemized_tax > Decimal('0.00') and raw_tax is not None:
            tax_diff = abs(itemized_tax - stated_tax)
            if tax_diff > cls.TOLERANCE:
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.TAX_CALCULATION_INCONSISTENCY.value,
                    severity=ValidationSeverity.ERROR.value,
                    field="quotation.tax",
                    expected_value=float(itemized_tax),
                    actual_value=float(stated_tax),
                    explanation=(
                        f"Tax calculation mismatch: Sum of itemized line taxes ({itemized_tax}) differs from "
                        f"stated header tax ({stated_tax}) by {tax_diff}."
                    ),
                ))

        # Check tax reasonableness: tax > subtotal when subtotal > 0
        base_for_tax = stated_subtotal if stated_subtotal is not None else calculated_subtotal
        if base_for_tax > Decimal('0.00') and stated_tax > base_for_tax:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.TAX_CALCULATION_INCONSISTENCY.value,
                severity=ValidationSeverity.WARNING.value,
                field="quotation.tax",
                expected_value=f"< {base_for_tax}",
                actual_value=float(stated_tax),
                explanation=f"Stated tax ({stated_tax}) exceeds the entire subtotal ({base_for_tax}).",
            ))

        # 5. Grand Total Calculation & Reconciliation
        base_subtotal = stated_subtotal if stated_subtotal is not None else calculated_subtotal
        expected_grand_total = QuotationCalculator.calculate_grand_total(
            subtotal=base_subtotal,
            tax=stated_tax,
            shipping=stated_shipping,
            discount=stated_discount,
        )
        report.calculated_grand_total = expected_grand_total

        if stated_grand_total is not None:
            grand_diff = abs(stated_grand_total - expected_grand_total)
            report.total_variance = grand_diff
            if grand_diff > cls.TOLERANCE:
                report.add_flag(ValidationFlag(
                    flag_type=ValidationFlagType.GRAND_TOTAL_INCONSISTENCY.value,
                    severity=ValidationSeverity.ERROR.value,
                    field="quotation.grand_total",
                    expected_value=float(expected_grand_total),
                    actual_value=float(stated_grand_total),
                    explanation=(
                        f"Grand Total discrepancy: Stated grand total ({stated_grand_total}) differs from "
                        f"expected ({base_subtotal} - discount {stated_discount} + tax {stated_tax} + shipping {stated_shipping} = {expected_grand_total}) "
                        f"by {grand_diff}."
                    ),
                ))
        else:
            report.add_flag(ValidationFlag(
                flag_type=ValidationFlagType.REQUIRED_FIELD_MISSING.value,
                severity=ValidationSeverity.WARNING.value,
                field="quotation.grand_total",
                expected_value=float(expected_grand_total),
                actual_value=None,
                explanation="Quotation document does not state an explicit grand total. System calculated grand total was assigned.",
            ))
