    MISSING_QUOTATION_NUMBER = "MISSING_QUOTATION_NUMBER"
    INVALID_DATE_FORMAT = "INVALID_DATE_FORMAT"
    DATE_ORDER_INVERTED = "DATE_ORDER_INVERTED"
    DATE_OUT_OF_RANGE = "DATE_OUT_OF_RANGE"
    NEGATIVE_QUANTITY = "NEGATIVE_QUANTITY"
    NEGATIVE_PRICE = "NEGATIVE_PRICE"
    INVALID_CURRENCY = "INVALID_CURRENCY"
    QUANTITY_INCONSISTENCY = "QUANTITY_INCONSISTENCY"
    INCORRECT_LINE_TOTAL = "INCORRECT_LINE_TOTAL"
    SUBTOTAL_INCONSISTENCY = "SUBTOTAL_INCONSISTENCY"
    TAX_CALCULATION_INCONSISTENCY = "TAX_CALCULATION_INCONSISTENCY"
